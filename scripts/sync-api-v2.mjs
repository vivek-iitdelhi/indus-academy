#!/usr/bin/env node
// Mirrors every /api/v1 route into /api/v2 as a re-export. v2 is v1 plus stricter rules, which the
// handlers apply when the path starts with /api/v2 (isV2 in src/app/api/v1/_learners.ts). Run it
// after adding or removing a v1 route: `node scripts/sync-api-v2.mjs` (it rewrites src/app/api/v2).
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const root = new URL("../src/app/api/", import.meta.url).pathname;
const v1 = join(root, "v1");
const v2 = join(root, "v2");
const METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE"];

const routes = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? routes(join(dir, e.name)) : e.name === "route.ts" ? [join(dir, e.name)] : [],
  );

rmSync(v2, { recursive: true, force: true });
for (const file of routes(v1)) {
  const source = readFileSync(file, "utf8");
  const methods = METHODS.filter((m) => new RegExp(`export (const|async function) ${m}\\b`).test(source));
  if (/export const (dynamic|runtime|maxDuration|revalidate)\b/.test(source)) {
    throw new Error(`${relative(root, file)} has segment config, which can't be re-exported: copy it by hand`);
  }
  const target = join(v2, relative(v1, file));
  mkdirSync(dirname(target), { recursive: true });
  const from = `@/app/api/v1/${relative(v1, file).replace(/\.ts$/, "")}`;
  writeFileSync(target, `// Generated by scripts/sync-api-v2.mjs: v2 runs the v1 handler, which applies v2's rules.\nexport { ${methods.join(", ")} } from "${from}";\n`);
}
console.log(`v2: ${routes(v2).length} routes`);
